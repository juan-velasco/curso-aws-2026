-- Estrella de gold: importes en EUR. Las claves subrogadas las genera Redshift.

CREATE TABLE IF NOT EXISTS gold.dim_cliente (
  cliente_sk  BIGINT GENERATED BY DEFAULT AS IDENTITY(1,1),
  cliente_id  VARCHAR(20) NOT NULL,
  segmento    VARCHAR(20),
  provincia   VARCHAR(60),
  pais        VARCHAR(2),
  valid_from  DATE NOT NULL,
  valid_to    DATE NOT NULL,
  is_current  BOOLEAN NOT NULL
) DISTSTYLE ALL SORTKEY (cliente_id, valid_from);

-- Ventas sin cliente identificado
INSERT INTO gold.dim_cliente (cliente_sk, cliente_id, segmento, provincia, pais, valid_from, valid_to, is_current)
SELECT -1, 'N/D', 'Desconocido', NULL, NULL, DATE '1900-01-01', DATE '9999-12-31', true
WHERE NOT EXISTS (SELECT 1 FROM gold.dim_cliente WHERE cliente_sk = -1);

CREATE TABLE IF NOT EXISTS gold.dim_producto (
  producto_sk BIGINT GENERATED BY DEFAULT AS IDENTITY(1,1),
  producto_id VARCHAR(30) NOT NULL,
  modelo      VARCHAR(10),
  color       VARCHAR(20),
  talla       VARCHAR(5),
  familia     VARCHAR(30),
  temporada   VARCHAR(10),
  valid_from  DATE NOT NULL,
  valid_to    DATE NOT NULL,
  is_current  BOOLEAN NOT NULL
) DISTSTYLE KEY DISTKEY (producto_sk);

CREATE TABLE IF NOT EXISTS gold.dim_tienda (
  tienda_sk     BIGINT GENERATED BY DEFAULT AS IDENTITY(1,1),
  tienda_id     VARCHAR(20) NOT NULL,
  nombre        VARCHAR(60),
  pais          VARCHAR(2),
  region        VARCHAR(20),
  ciudad        VARCHAR(40),
  formato       VARCHAR(20),
  superficie_m2 INT
) DISTSTYLE ALL;

-- Copia de tienda y país para gold.mv_ventas_diarias: una vista materializada no puede
-- basarse en dim_tienda, que tiene seguridad a nivel de fila (07_permisos_demo.sql)
CREATE TABLE IF NOT EXISTS gold.tienda_pais (
  tienda_sk BIGINT NOT NULL,
  pais      VARCHAR(2)
) DISTSTYLE ALL;

CREATE TABLE IF NOT EXISTS gold.dim_fecha (
  fecha_sk         INT NOT NULL,
  fecha            DATE NOT NULL,
  anio             INT,
  mes              INT,
  nombre_mes       VARCHAR(20),
  semana_iso       INT,
  dia_semana       INT,
  nombre_dia       VARCHAR(20),
  es_fin_de_semana BOOLEAN,
  temporada        VARCHAR(2),
  es_rebajas       BOOLEAN,
  es_festivo       BOOLEAN
) DISTSTYLE ALL SORTKEY (fecha_sk);

CREATE TABLE IF NOT EXISTS gold.fct_ventas (
  fecha_sk      INT NOT NULL,
  cliente_sk    BIGINT NOT NULL,
  producto_sk   BIGINT NOT NULL,
  tienda_sk     BIGINT NOT NULL,
  ticket_id     VARCHAR(40),
  linea         INT,
  unidades      INT,
  importe_bruto DECIMAL(12,2),
  descuento     DECIMAL(12,2)
) DISTSTYLE KEY DISTKEY (producto_sk) SORTKEY (fecha_sk);
